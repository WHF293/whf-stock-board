/**
 * 内置 Skill（随应用常驻，不可删除 / 不可编辑）
 *
 * 与 `BUILTIN_SUBAGENTS` 同一设计语言：常量数组、随应用发货、用户不可删。
 * 用户自装 skill 走 `skill-zip.ts` → `appData/agent-workspace/<dir>/SKILL.md` 那条链路，
 * 与本文件的内置项在运行时**合并进同一套虚拟文件系统**（见 utils/agent-skill-files.ts）。
 *
 * 与子 agent 提示词的分工（渐进披露的本意）：
 * - 子 agent 的 systemPrompt 讲**角色、证据规则、输出结构**（每次运行都进上下文）；
 * - skill 正文讲**方法细节与检查表**（只有子 agent 判定需要时才由它主动读取）。
 *   因此这里不重复提示词里已有的硬规则，只补「怎么做」。
 *
 * ⚠️ 约束（来自 deepagents 的解析实现）：
 * - SKILL.md 必须有 YAML frontmatter，且 `name` / `description` 均非空；
 * - `description` ≤ 1024 字符（超长会被截断）；
 * - 正文经 backend.read 读取（默认 limit 500 行），**单个 skill 控制在 500 行内**；
 * - `name` 用 kebab-case，与 frontmatter 的 name 保持一致。
 */

/** 内置 skill 定义 */
export interface BuiltinSkill {
  /**
   * 授权用资源 id
   *
   * ⚠️ 内置 skill 不在 `skill` 表里（是随应用发货的常量），没有自增 id；
   * 沿用与内置 subagent 相同的**负数 id 约定**（子 agent -1~-7 / MCP -1~-3 各自独立），
   * 使其能与用户自装 skill（正数 id）共用 `resource_grant` 表授权。
   */
  id: number;
  /** skill 名（kebab-case，须与 SKILL.md frontmatter 的 name 一致） */
  name: string;
  /** 一句话描述（进提示词的 skill 列表，决定模型何时想起它） */
  description: string;
  /** SKILL.md 正文（不含 frontmatter；组装时由 buildSkillMarkdown 拼接） */
  body: string;
}

